%% ==================== Local functions ====================

function neighborIndex = ...
        generateRandomKOutNetwork( ...
            n, ...
            targetOutDegree)
%GENERATERANDOMKOUTNETWORK
% Generate a strongly connected directed random k-out network.
%
% The first outgoing edge of each node forms a directed ring. The
% remaining outgoing neighbors are sampled without replacement, with
% self-loops and duplicate outgoing edges excluded.

    outDegree = ...
        min(targetOutDegree, n - 1);

    neighborIndex = ...
        zeros(n, outDegree, 'uint32');

    nodeIdentifiers = ...
        uint32((1:n)');

    numberOfNodesUint32 = ...
        uint32(n);

    % Directed ring guaranteeing strong connectivity.
    neighborIndex(:, 1) = ...
        mod( ...
            nodeIdentifiers, ...
            numberOfNodesUint32) ...
        + uint32(1);

    for edgeIndex = 2:outDegree

        randomOffset = ...
            randi( ...
                n - 1, ...
                n, ...
                1, ...
                'uint32');

        destination = ...
            mod( ...
                nodeIdentifiers ...
                - uint32(1) ...
                + randomOffset, ...
                numberOfNodesUint32) ...
            + uint32(1);

        invalid = ...
            false(n, 1);

        for previousEdge = 1:(edgeIndex - 1)

            invalid = ...
                invalid ...
                | destination ...
                == neighborIndex(:, previousEdge);
        end

        invalidRows = ...
            find(invalid);

        while ~isempty(invalidRows)

            replacementOffset = ...
                randi( ...
                    n - 1, ...
                    numel(invalidRows), ...
                    1, ...
                    'uint32');

            replacementDestination = ...
                mod( ...
                    nodeIdentifiers(invalidRows) ...
                    - uint32(1) ...
                    + replacementOffset, ...
                    numberOfNodesUint32) ...
                + uint32(1);

            replacementInvalid = ...
                false(numel(invalidRows), 1);

            for previousEdge = 1:(edgeIndex - 1)

                replacementInvalid = ...
                    replacementInvalid ...
                    | replacementDestination ...
                    == neighborIndex( ...
                        invalidRows, ...
                        previousEdge);
            end

            acceptedRows = ...
                invalidRows(~replacementInvalid);

            destination(acceptedRows) = ...
                replacementDestination(~replacementInvalid);

            invalidRows = ...
                invalidRows(replacementInvalid);
        end

        neighborIndex(:, edgeIndex) = ...
            destination;
    end
end

function rightHandSide = ...
        generateWeightedRightHandSide( ...
            n, ...
            outDegree, ...
            theta, ...
            numberOfAlternatives, ...
            utilityByRank, ...
            maximumEdgeCost, ...
            blockSize)
%GENERATEWEIGHTEDRIGHTHANDSIDE
% Construct the right-hand side
%
%   R = D*U^I - K*e,
%
% where
%
%   K = W .* C
%
% and
%
%   kappa_jk(a_i) = w_jk*c_jk(a_i).
%
% In the synthetic k-out network, all non-self outgoing edges have
% weight
%
%   w_jk = (1-theta)/outDegree.
%
% Thus, for each node and alternative,
%
%   sum_k kappa_jk
%       = ((1-theta)/outDegree) * sum_k c_jk.

    nonSelfEdgeWeight = ...
        (1 - theta) / outDegree;

    rightHandSide = ...
        zeros(n, numberOfAlternatives);

    for blockStart = 1:blockSize:n

        blockEnd = ...
            min( ...
                n, ...
                blockStart + blockSize - 1);

        blockLength = ...
            blockEnd - blockStart + 1;

        %% Random preference rankings

        randomPreferenceScores = ...
            rand( ...
                blockLength, ...
                numberOfAlternatives, ...
                'single');

        [~, preferenceOrder] = ...
            sort( ...
                randomPreferenceScores, ...
                2, ...
                'ascend');

        intrinsicUtility = ...
            zeros( ...
                blockLength, ...
                numberOfAlternatives);

        rowIndices = ...
            (1:blockLength)';

        for rankIndex = 1:numberOfAlternatives

            linearIndices = ...
                sub2ind( ...
                    [blockLength, numberOfAlternatives], ...
                    rowIndices, ...
                    preferenceOrder(:, rankIndex));

            intrinsicUtility(linearIndices) = ...
                utilityByRank(rankIndex);
        end

        %% Baseline alternative-dependent maintenance costs

        baselineOutgoingCostSum = ...
            zeros( ...
                blockLength, ...
                numberOfAlternatives);

        for alternativeIndex = 1:numberOfAlternatives

            alternativeBaselineCost = ...
                zeros(blockLength, 1);

            for edgeIndex = 1:outDegree

                alternativeBaselineCost = ...
                    alternativeBaselineCost ...
                    + double( ...
                        randi( ...
                            [0, maximumEdgeCost], ...
                            blockLength, ...
                            1, ...
                            'uint8'));
            end

            baselineOutgoingCostSum(:, alternativeIndex) = ...
                alternativeBaselineCost;
        end

        %% Empathy-weighted effective maintenance costs

        effectiveOutgoingCostSum = ...
            nonSelfEdgeWeight ...
            * baselineOutgoingCostSum;

        %% R = D*U^I - (W.*C)e

        rightHandSide( ...
            blockStart:blockEnd, :) = ...
            theta * intrinsicUtility ...
            - effectiveOutgoingCostSum;
    end
end

function result = ...
        runMatrixFreeICE( ...
            neighborIndex, ...
            rightHandSide, ...
            alpha, ...
            theta, ...
            maximumIterations)
%RUNMATRIXFREEICE
% Run ICE/FI-ICE without explicitly storing the n-by-n matrix.
%
% The supplied rightHandSide already contains the empathy-weighted
% maintenance cost:
%
%   R = D*U^I - (W.*C)e.

    [numberOfNodes, numberOfAlternatives] = ...
        size(rightHandSide);

    outDegree = ...
        size(neighborIndex, 2);

    edgeWeight = ...
        (1 - theta) / outDegree;

    %% Compute max_i Delta(a_i,alpha)

    maximumDelta = 0;

    for alternativeIndex = 1:numberOfAlternatives

        alternativeDelta = ...
            max( ...
                abs( ...
                    rightHandSide(:, alternativeIndex) ...
                    - theta * alpha));

        maximumDelta = ...
            max( ...
                maximumDelta, ...
                alternativeDelta);
    end

    activeAlternatives = ...
        1:numberOfAlternatives;

    currentUtility = ...
        alpha ...
        * ones( ...
            numberOfNodes, ...
            numberOfAlternatives);

    %% ICE/FI-ICE iterations

    for iteration = 1:maximumIterations

        nextUtility = ...
            rightHandSide(:, activeAlternatives);

        for edgeIndex = 1:outDegree

            nextUtility = ...
                nextUtility ...
                + edgeWeight ...
                .* currentUtility( ...
                    neighborIndex(:, edgeIndex), :);
        end

        currentWelfare = ...
            sum(nextUtility, 1);

        maximumIterativeWelfare = ...
            max(currentWelfare);

        welfareGap = ...
            maximumIterativeWelfare ...
            - currentWelfare;

        eliminationThreshold = ...
            2 ...
            * numberOfNodes ...
            * (1 - theta)^iteration ...
            / theta ...
            * maximumDelta;

        numericalScale = ...
            max( ...
                [ ...
                    1, ...
                    abs(maximumIterativeWelfare), ...
                    abs(eliminationThreshold) ...
                ]);

        numericalTolerance = ...
            64 * eps(numericalScale);

        % Strict elimination rule:
        %
        % eliminate if gap > threshold + numerical tolerance.
        keepAlternative = ...
            welfareGap ...
            <= eliminationThreshold ...
            + numericalTolerance;

        activeAlternatives = ...
            activeAlternatives(keepAlternative);

        currentUtility = ...
            nextUtility(:, keepAlternative);

        if numel(activeAlternatives) <= 1
            break;
        end
    end

    result = struct;

    result.candidateSet = ...
        activeAlternatives;

    result.iterations = ...
        iteration;

    result.terminatedWithSingleton = ...
        numel(activeAlternatives) == 1;
end

function [welfare, coefficientMatrix, adjointWeight] = ...
        solveDirectReferenceCore( ...
            neighborIndex, ...
            rightHandSide, ...
            theta)
%SOLVEDIRECTREFERENCECORE
% Sparse direct reference calculation.
%
% Let
%
%   A = I - (W-D),
%   A*U = R.
%
% Then
%
%   e'*U = e'*A^(-1)*R = z'*R,
%
% where
%
%   A'*z = e.
%
% This obtains the exact social welfare of all alternatives using one
% sparse adjoint solve rather than explicitly forming A^(-1).

    numberOfNodes = ...
        size(neighborIndex, 1);

    outDegree = ...
        size(neighborIndex, 2);

    edgeWeight = ...
        (1 - theta) / outDegree;

    sourceNodes = ...
        repmat( ...
            (1:numberOfNodes)', ...
            outDegree, ...
            1);

    destinationNodes = ...
        double(neighborIndex(:));

    edgeWeights = ...
        edgeWeight ...
        * ones( ...
            numberOfNodes * outDegree, ...
            1);

    iterationMatrix = ...
        sparse( ...
            sourceNodes, ...
            destinationNodes, ...
            edgeWeights, ...
            numberOfNodes, ...
            numberOfNodes);

    clear sourceNodes destinationNodes edgeWeights

    coefficientMatrix = ...
        speye(numberOfNodes) ...
        - iterationMatrix;

    clear iterationMatrix

    adjointWeight = ...
        coefficientMatrix.' ...
        \ ones(numberOfNodes, 1);

    welfare = ...
        adjointWeight.' ...
        * rightHandSide;
end

function [medianSeconds, lastResult] = ...
        timeICEMethod( ...
            neighborIndex, ...
            rightHandSide, ...
            alpha, ...
            theta, ...
            maximumIterations, ...
            numberOfTimingRepeats)
%TIMEICEMETHOD
% Return the median time over repeated executions.

    elapsedSeconds = ...
        zeros(numberOfTimingRepeats, 1);

    lastResult = [];

    for timingIndex = 1:numberOfTimingRepeats

        timingIdentifier = tic;

        lastResult = ...
            runMatrixFreeICE( ...
                neighborIndex, ...
                rightHandSide, ...
                alpha, ...
                theta, ...
                maximumIterations);

        elapsedSeconds(timingIndex) = ...
            toc(timingIdentifier);
    end

    medianSeconds = ...
        median(elapsedSeconds);
end

function [medianSeconds, lastWelfare, relativeResidual] = ...
        timeDirectMethod( ...
            neighborIndex, ...
            rightHandSide, ...
            theta, ...
            numberOfTimingRepeats)
%TIMEDIRECTMETHOD
% Return the median sparse-direct time and the final residual.

    elapsedSeconds = ...
        zeros(numberOfTimingRepeats, 1);

    lastWelfare = [];
    coefficientMatrix = [];
    adjointWeight = [];

    for timingIndex = 1:numberOfTimingRepeats

        timingIdentifier = tic;

        [lastWelfare, ...
            coefficientMatrix, ...
            adjointWeight] = ...
            solveDirectReferenceCore( ...
                neighborIndex, ...
                rightHandSide, ...
                theta);

        elapsedSeconds(timingIndex) = ...
            toc(timingIdentifier);
    end

    medianSeconds = ...
        median(elapsedSeconds);

    numberOfNodes = ...
        size(neighborIndex, 1);

    residualVector = ...
        coefficientMatrix.' ...
        * adjointWeight ...
        - ones(numberOfNodes, 1);

    relativeResidual = ...
        norm(residualVector, inf) ...
        / ( ...
            norm(coefficientMatrix, 1) ...
            * norm(adjointWeight, inf) ...
            + 1);
end

function numberOfTimingRepeats = ...
        chooseTimingRepeats(numberOfNodes)
%CHOOSETIMINGREPEATS
% Internal repetitions reduce timer noise. They are distinct from Monte
% Carlo replications.

    if numberOfNodes <= 100

        numberOfTimingRepeats = 30;

    elseif numberOfNodes <= 1000

        numberOfTimingRepeats = 5;

    else

        numberOfTimingRepeats = 1;
    end
end

function percentileValue = ...
        localPercentile( ...
            values, ...
            percentile)
%LOCALPERCENTILE
% Toolbox-independent linearly interpolated percentile.

    values = ...
        sort(values(isfinite(values)));

    numberOfValues = ...
        numel(values);

    if numberOfValues == 0

        percentileValue = NaN;
        return;
    end

    if numberOfValues == 1

        percentileValue = values(1);
        return;
    end

    position = ...
        1 ...
        + (numberOfValues - 1) ...
        * percentile / 100;

    lowerIndex = ...
        floor(position);

    upperIndex = ...
        ceil(position);

    interpolationWeight = ...
        position - lowerIndex;

    percentileValue = ...
        values(lowerIndex) ...
        * (1 - interpolationWeight) ...
        + values(upperIndex) ...
        * interpolationWeight;
end

function memoryGB = ...
        estimateMatrixFreeMemoryGB( ...
            numberOfNodes, ...
            outDegree, ...
            numberOfAlternatives)
%ESTIMATEMATRIXFREEMEMORYGB
% Approximate memory for neighbor indices and main double arrays.

    memoryBytes = ...
        4 * numberOfNodes * outDegree ...
        + 3 ...
        * 8 ...
        * numberOfNodes ...
        * numberOfAlternatives;

    memoryGB = ...
        memoryBytes / 1024^3;
end

function memoryGB = ...
        estimateSparseInputMemoryGB( ...
            numberOfNodes, ...
            outDegree)
%ESTIMATESPARSEINPUTMEMORYGB
% Lower-bound storage estimate for A = I-(W-D).
% Sparse factorization fill-in is not included.

    approximateNonzeros = ...
        numberOfNodes ...
        * (outDegree + 1);

    valuesAndRowIndicesBytes = ...
        16 * approximateNonzeros;

    columnPointerBytes = ...
        8 * (numberOfNodes + 1);

    memoryGB = ...
        ( ...
            valuesAndRowIndicesBytes ...
            + columnPointerBytes) ...
        / 1024^3;
end

