%% Synthetic-network scalability benchmark for weighted-cost ICE
% MATLAB R2024b
%
% Cost model:
%   kappa_jk(a_i) = w_jk * c_jk(a_i)
%
% Global utility system:
%   U = (W-D)U + D*U^I - (W.*C)e
%
% Compared methods:
%   1. Matrix-free ICE/FI-ICE;
%   2. Sparse-adjoint direct reference method.
%
% Timing convention:
%   Network, preference, and cost generation are excluded from the solver
%   times because they are shared by both methods. Generation time is
%   recorded separately.
%
% Outputs:
%   1. Raw results CSV;
%   2. Summary results CSV;
%   3. Runtime-scaling figure;
%   4. Paired-speedup figure;
%   5. ICE-iteration figure;
%   6. Checkpoint MAT file.

clearvars;
clc;
close all;

%% 1. Experimental configuration

% Network sizes used in the manuscript.
nodeCounts = [10, 50, 100, 500, 1000, 5000, 10000];

% One thousand independent instances for each network size.
replicationCounts = ...
    1000 * ones(size(nodeCounts));

% For a short smoke test, temporarily use:
% replicationCounts = 5 * ones(size(nodeCounts));

% Network parameters.
targetOutDegree = 8;
theta = 0.4;

% Alternative and preference parameters.
numberOfAlternatives = 8;
utilityByRank = 80:-10:10;
alpha = min(utilityByRank);

% Baseline maintenance costs:
% c_jk(a_i) belongs to {0,1,2}.
maximumEdgeCost = 5;

% FI-ICE maximum-iteration safeguard.
maximumICEIterations = 500;

% Attempt the sparse direct method for every configured network size.
directNodeLimit = max(nodeCounts);

% Continue if MATLAB catches a direct-solver failure.
continueAfterDirectFailure = true;

% Block size for memory-controlled preference and cost generation.
generationBlockSize = 250000;

% Reproducibility seed.
masterSeed = 20260827;

% Output options.
writeResults = true;
saveFigures = true;
saveCheckpointAfterEveryRun = true;

%% 2. Output locations

scriptDirectory = ...
    fileparts(mfilename('fullpath'));

if isempty(scriptDirectory)
    scriptDirectory = pwd;
end

outputDirectory = ...
    fullfile( ...
        scriptDirectory, ...
        'synthetic_ICE_weighted_cost_results');

if ~isfolder(outputDirectory)
    mkdir(outputDirectory);
end

checkpointPath = ...
    fullfile( ...
        outputDirectory, ...
        'synthetic_weighted_cost_ICE_checkpoint.mat');

%% 3. Store experimental configuration

config = struct;

config.nodeCounts = nodeCounts;
config.replicationCounts = replicationCounts;
config.targetOutDegree = targetOutDegree;
config.theta = theta;
config.numberOfAlternatives = numberOfAlternatives;
config.utilityByRank = utilityByRank;
config.alpha = alpha;
config.maximumEdgeCost = maximumEdgeCost;
config.maximumICEIterations = maximumICEIterations;
config.directNodeLimit = directNodeLimit;
config.generationBlockSize = generationBlockSize;
config.masterSeed = masterSeed;

config.costModel = ...
    "kappa_jk(a_i) = w_jk*c_jk(a_i)";

config.solverTimingConvention = ...
    "Generation excluded; solver cores timed separately";

%% 4. Display benchmark settings

fprintf('\n');
fprintf('Weighted-cost ICE scalability benchmark\n');
fprintf('=======================================\n');
fprintf('Network model       : strongly connected random k-out\n');
fprintf('Network sizes       : %s\n', mat2str(nodeCounts));
fprintf('Replications/size   : %s\n', mat2str(replicationCounts));
fprintf('Target out-degree   : %d\n', targetOutDegree);
fprintf('Self-weight theta   : %.2f\n', theta);
fprintf('Non-self edge weight: %.6f\n', ...
    (1 - theta) / targetOutDegree);
fprintf('Alternatives        : %d\n', numberOfAlternatives);
fprintf('Baseline costs      : integers in {0,...,%d}\n', ...
    maximumEdgeCost);
fprintf('Effective cost      : kappa_jk = w_jk*c_jk\n');
fprintf('Direct-method limit : %.0f nodes\n', directNodeLimit);
fprintf('Maximum ICE iter.   : %d\n\n', maximumICEIterations);

%% 5. Warm up MATLAB JIT

rng(masterSeed, 'twister');

warmupN = 100;

warmupNeighbors = ...
    generateRandomKOutNetwork( ...
        warmupN, ...
        targetOutDegree);

warmupRightHandSide = ...
    generateWeightedRightHandSide( ...
        warmupN, ...
        size(warmupNeighbors, 2), ...
        theta, ...
        numberOfAlternatives, ...
        utilityByRank, ...
        maximumEdgeCost, ...
        generationBlockSize);

runMatrixFreeICE( ...
    warmupNeighbors, ...
    warmupRightHandSide, ...
    alpha, ...
    theta, ...
    maximumICEIterations);

solveDirectReferenceCore( ...
    warmupNeighbors, ...
    warmupRightHandSide, ...
    theta);

clear warmupNeighbors warmupRightHandSide

%% 6. Preallocate raw results

maximumNumberOfRuns = ...
    sum(replicationCounts);

state = struct;

state.Nodes = ...
    zeros(maximumNumberOfRuns, 1);

state.Replication = ...
    zeros(maximumNumberOfRuns, 1);

state.InstanceSeed = ...
    zeros(maximumNumberOfRuns, 1);

state.GenerationSeconds = ...
    nan(maximumNumberOfRuns, 1);

state.ICESeconds = ...
    nan(maximumNumberOfRuns, 1);

state.DirectSeconds = ...
    nan(maximumNumberOfRuns, 1);

state.ICEIterations = ...
    nan(maximumNumberOfRuns, 1);

state.ICECandidateCount = ...
    nan(maximumNumberOfRuns, 1);

state.ICESelectedAlternative = ...
    nan(maximumNumberOfRuns, 1);

state.ICESingleton = ...
    false(maximumNumberOfRuns, 1);

state.DirectOptimalAlternative = ...
    nan(maximumNumberOfRuns, 1);

state.DirectOptimalCount = ...
    nan(maximumNumberOfRuns, 1);

state.DirectResidual = ...
    nan(maximumNumberOfRuns, 1);

state.ICEContainsDirectOptimum = ...
    nan(maximumNumberOfRuns, 1);

state.ICESameDecision = ...
    nan(maximumNumberOfRuns, 1);

state.DirectStatus = ...
    strings(maximumNumberOfRuns, 1);

state.DirectErrorMessage = ...
    strings(maximumNumberOfRuns, 1);

resultRow = 0;

%% 7. Monte Carlo benchmark

for sizeIndex = 1:numel(nodeCounts)

    n = nodeCounts(sizeIndex);

    numberOfReplications = ...
        replicationCounts(sizeIndex);

    actualOutDegree = ...
        min(targetOutDegree, n - 1);

    matrixFreeMemoryGB = ...
        estimateMatrixFreeMemoryGB( ...
            n, ...
            actualOutDegree, ...
            numberOfAlternatives);

    sparseInputMemoryGB = ...
        estimateSparseInputMemoryGB( ...
            n, ...
            actualOutDegree);

    availableMemoryGB = ...
        getAvailablePhysicalMemoryGB();

    fprintf('\n');
    fprintf('========================================\n');
    fprintf('n = %d\n', n);
    fprintf('Replications = %d\n', numberOfReplications);
    fprintf('Actual out-degree = %d\n', actualOutDegree);
    fprintf('Non-self edge weight = %.8f\n', ...
        (1 - theta) / actualOutDegree);
    fprintf('Estimated matrix-free arrays = %.3f GB\n', ...
        matrixFreeMemoryGB);
    fprintf('Sparse input storage lower bound = %.3f GB\n', ...
        sparseInputMemoryGB);

    if isfinite(availableMemoryGB)

        fprintf('Available physical memory = %.3f GB\n', ...
            availableMemoryGB);
    end

    fprintf(['NOTE: sparse storage estimate excludes factorization ' ...
        'fill-in.\n']);
    fprintf('========================================\n');

    for replicationIndex = 1:numberOfReplications

        resultRow = resultRow + 1;

        state.Nodes(resultRow) = ...
            n;

        state.Replication(resultRow) = ...
            replicationIndex;

        currentSeed = ...
            masterSeed ...
            + 1000000 * sizeIndex ...
            + replicationIndex;

        state.InstanceSeed(resultRow) = ...
            currentSeed;

        rng(currentSeed, 'twister');

        fprintf('\n');
        fprintf('n = %d, replication %d/%d\n', ...
            n, ...
            replicationIndex, ...
            numberOfReplications);

        %% 7.1 Generate a common weighted-cost instance

        generationTimer = tic;

        neighborIndex = ...
            generateRandomKOutNetwork( ...
                n, ...
                targetOutDegree);

        rightHandSide = ...
            generateWeightedRightHandSide( ...
                n, ...
                size(neighborIndex, 2), ...
                theta, ...
                numberOfAlternatives, ...
                utilityByRank, ...
                maximumEdgeCost, ...
                generationBlockSize);

        state.GenerationSeconds(resultRow) = ...
            toc(generationTimer);

        %% 7.2 Time ICE/FI-ICE

        numberOfTimingRepeats = ...
            chooseTimingRepeats(n);

        [state.ICESeconds(resultRow), iceResult] = ...
            timeICEMethod( ...
                neighborIndex, ...
                rightHandSide, ...
                alpha, ...
                theta, ...
                maximumICEIterations, ...
                numberOfTimingRepeats);

        state.ICEIterations(resultRow) = ...
            iceResult.iterations;

        state.ICECandidateCount(resultRow) = ...
            numel(iceResult.candidateSet);

        state.ICESingleton(resultRow) = ...
            numel(iceResult.candidateSet) == 1;

        if state.ICESingleton(resultRow)

            state.ICESelectedAlternative(resultRow) = ...
                iceResult.candidateSet;
        end

        state.DirectStatus(resultRow) = ...
            "pending";

        fprintf('  Generation time : %.6g s\n', ...
            state.GenerationSeconds(resultRow));

        fprintf('  ICE time        : %.6g s\n', ...
            state.ICESeconds(resultRow));

        fprintf('  ICE iterations  : %d\n', ...
            state.ICEIterations(resultRow));

        fprintf('  ICE candidates  : %s\n', ...
            mat2str(iceResult.candidateSet));

        %% 7.3 Save ICE result before direct factorization

        if saveCheckpointAfterEveryRun

            saveBenchmarkCheckpoint( ...
                checkpointPath, ...
                state, ...
                resultRow, ...
                config);
        end

        %% 7.4 Time sparse direct reference method

        directIsEnabled = ...
            n <= directNodeLimit;

        directWelfare = [];

        if directIsEnabled

            try

                availableBeforeDirectGB = ...
                    getAvailablePhysicalMemoryGB();

                if isfinite(availableBeforeDirectGB)

                    fprintf(['  Available memory before direct ' ...
                        'solve: %.3f GB\n'], ...
                        availableBeforeDirectGB);
                end

                fprintf('  Starting sparse direct solution...\n');

                [state.DirectSeconds(resultRow), ...
                    directWelfare, ...
                    state.DirectResidual(resultRow)] = ...
                    timeDirectMethod( ...
                        neighborIndex, ...
                        rightHandSide, ...
                        theta, ...
                        numberOfTimingRepeats);

                state.DirectStatus(resultRow) = ...
                    "completed";

                state.DirectErrorMessage(resultRow) = ...
                    "";

                fprintf('  Direct time     : %.6g s\n', ...
                    state.DirectSeconds(resultRow));

                fprintf('  Direct residual : %.3e\n', ...
                    state.DirectResidual(resultRow));

            catch directError

                state.DirectSeconds(resultRow) = ...
                    NaN;

                state.DirectResidual(resultRow) = ...
                    NaN;

                errorIdentifier = ...
                    string(directError.identifier);

                if strlength(errorIdentifier) == 0

                    errorIdentifier = ...
                        "unidentified-error";
                end

                state.DirectStatus(resultRow) = ...
                    "failed:" + errorIdentifier;

                state.DirectErrorMessage(resultRow) = ...
                    string(directError.message);

                fprintf(2, ...
                    '  Direct method failed: %s\n', ...
                    char(errorIdentifier));

                fprintf(2, ...
                    '  Error message: %s\n', ...
                    directError.message);

                if ~continueAfterDirectFailure

                    rethrow(directError);
                end
            end

        else

            state.DirectStatus(resultRow) = ...
                "not-attempted:size-limit";

            state.DirectErrorMessage(resultRow) = ...
                "Node count exceeds directNodeLimit.";
        end

        %% 7.5 Compare ICE with the direct reference

        if ~isempty(directWelfare)

            maximumDirectWelfare = ...
                max(directWelfare);

            directTolerance = ...
                1e-9 ...
                * max( ...
                    1, ...
                    max(abs(directWelfare)));

            directOptimalSet = ...
                find( ...
                    abs( ...
                        directWelfare ...
                        - maximumDirectWelfare) ...
                    <= directTolerance);

            state.DirectOptimalCount(resultRow) = ...
                numel(directOptimalSet);

            state.DirectOptimalAlternative(resultRow) = ...
                directOptimalSet(1);

            state.ICEContainsDirectOptimum(resultRow) = ...
                all( ...
                    ismember( ...
                        directOptimalSet, ...
                        iceResult.candidateSet));

            state.ICESameDecision(resultRow) = ...
                state.ICESingleton(resultRow) ...
                && ismember( ...
                    iceResult.candidateSet, ...
                    directOptimalSet);

            fprintf('  Direct optimum  : %s\n', ...
                mat2str(directOptimalSet));

            fprintf('  Decision match  : %d\n', ...
                state.ICESameDecision(resultRow));
        end

        %% 7.6 Save completed replication

        if saveCheckpointAfterEveryRun

            saveBenchmarkCheckpoint( ...
                checkpointPath, ...
                state, ...
                resultRow, ...
                config);
        end

        clear neighborIndex rightHandSide
        clear iceResult directWelfare directOptimalSet

        drawnow;
    end
end

